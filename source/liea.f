      subroutine cpsnf(pow,fa,fm,ga,gm)
c this subroutine computes the power of a static normal form map:
c mapg=(mapf)**pow
c Written by Alex Dragt, Fall 1986
c
      include 'impli.inc'
      include 'param.inc'
c
c Calling arrays 
      dimension fa(monoms),ga(monoms)
      dimension fm(6,6),gm(6,6)
c
c Local arrays
      dimension ta(monoms)
c
c clear output array
      call clear(ta,gm)
c
c begin calculation
c
c compute phase advances
      cwx=fm(1,1)
      swx=fm(1,2)
      wx=atan2(swx,cwx)
      cwy=fm(3,3)
      swy=fm(3,4)
      wy=atan2(swy,cwy)
c compute momentum compaction
      wt=fm(5,6)
c compute new quantities
      pwx=pow*wx
      cpwx=cos(pwx)
      spwx=sin(pwx)
      pwy=pow*wy
      cpwy=cos(pwy)
      spwy=sin(pwy)
      pwt=pow*wt
c compute new matrix
      gm(1,1)=cpwx
      gm(1,2)=spwx
      gm(2,1)=-spwx
      gm(2,2)=cpwx
      gm(3,3)=cpwy
      gm(3,4)=spwy
      gm(4,3)=-spwy
      gm(4,4)=cpwy
      gm(5,5)=1.d0
      gm(5,6)=pwt
      gm(6,6)=1.d0
c compute polynomials of old normal form map in static resonance basis
      call ctosr(fa,ga)
c pick out those terms which are allowed to be nonzero
      ta(28)=ga(28)
      ta(29)=ga(29)
      ta(30)=ga(30)
      ta(84)=ga(84)
      ta(85)=ga(85)
      ta(86)=ga(86)
      ta(87)=ga(87)
      ta(88)=ga(88)
      ta(89)=ga(89)
c compute polynomials of new map in static resonance basis
      call csmul(pow,ta,ta)
c transform back to cartesian basis
      call srtoc(ta,ga)
c
      return
      end
