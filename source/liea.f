      subroutine xform(f,no,m,matold,l)
c
c     Transforms a polynomial of degree no, f
c     by the lie transformation whose
c     matrix representation is m.  the coefficients
c     of the resultant polynomial are stored in the
c     the array l which thus contains the coefficients of f(m*z).
c
      include 'impli.inc'
      include 'param.inc'
      double precision l,m,f
      dimension f(monoms),l(monoms)
      double precision temp(monoms)
      dimension m(6,6)
c  expon = table of exponents
      include 'expon.inc'
c  vblist = table of variables occuring in monomial
      include 'vblist.inc'
c     
      include 'prodex.inc'
      include 'len.inc'
      include 'ind.inc'
c
c     initialise arrays
c
      do 10 kp=1,len(no)
      temp(kp) = 0.0d0
   10 continue
      do 100 n= len(no-1)+1,len(no)
        if(f(n).eq.0.0d0) goto 100
        do 101 kp=1,len(no-1)
          temp(kp) = 0.0d0
  101   continue
        do 102 k=1,6
          if(m(vblist(1,n),k).eq.0.0d0) goto 102
          temp(k) = f(n)*m(vblist(1,n),k)
  102    continue
        do 110 ior=1,no-1
          k1 = vblist(ior+1,n)
          if(ior.eq.1) then
            n1 = 1
          else
            n1=len(ior-1)+1
          endif
          do 112 k=1,6
            if(m(k1,k).eq.0.0d0) goto 112
            xm = m(k1,k)
cdir$ ivdep
            do 111 nn=n1,len(ior)
            temp(prodex(k,nn)) = temp(prodex(k,nn)) + temp(nn)*xm
  111       continue
  112     continue
  110   continue
  100 continue
      do 200 nn=len(no-1)+1,len(no)
        l(nn) = temp(nn)
  200 continue
c
      return
      end
