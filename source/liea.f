      subroutine concat(f,mf,g,mg,h,mh)
c     concatenates a map with linear piece
c     represented by a matrix mf and nonlinearities
c     represented by exp:f:, with a map whose
c     linear piece has matrix representation mg
c     and whose nonlinearities are represented by exp:g:
c
c     the result is a map with linearities possessing
c     a matrix representation mh=mg*mf
c     and with nonlinearities generated by exp:h:
c
c     the "f" map is assumed to occur first in the beamline
c     the "g" map is encountered second
c     that is, one has the map relation h=f*g
c
c     Written by David Douglas, ca 1982
c     Modified by Alex Dragt 24 June 1988 so that the routine
c     still works even when the map h,mh is one of the maps
c     f,mf or g,mg.    
c
      include 'impli.inc'
      include 'param.inc'
c
c calling arrays
      dimension f(monoms),g(monoms),h(monoms)
      double precision mf(6,6),mg(6,6),mh(6,6)
c
c working arrays
      dimension t1(monoms),t2(monoms)
      double precision mt1(6,6),mt2(6,6)
c
      include 'symp.inc'
c
c compute mt1=mg*mf and mt2=mgtransposed*jm
c
      call mclear(mt1)
      call mclear(mt2)
      do 40 j=1,6
      do 30 i=1,6
      do 20 k=1,6
      mt1(i,j)=mt1(i,j)+mg(i,k)*mf(k,j)
      mt2(i,j)=mt2(i,j)+mg(k,i)*jm(k,j)
   20 continue
   30 continue
   40 continue
c
c set mh=mt1
c
      do 31 j=1,6
      do 21 i=1,6
      mh(i,j)=mt1(i,j)
   21 continue
   31 continue
c
c compute mt1=jmtransposed*mt2=inverse of mg
c
      call mclear(mt1)
      do 42 j=1,6
      do 32 i=1,6
      do 22 k=1,6
      mt1(i,j)=mt1(i,j)+jm(k,i)*mt2(k,j)
   22 continue
   32 continue
   42 continue
c
c compute t1=result of transforming f by mt1
c
      call xform(f,3,mt1,0,t1)
      call xform(f,4,mt1,1,t1)
c
c compute t2=[t1,g]
c
      call pbkt(t1,3,g,3,t2)
c
c compute degree-three coefficients
c
      do 50 k=28,83
      h(k)=g(k)+t1(k)
   50 continue
c
c compute degree-four coefficients
c
      do 60 k=84,209
      h(k)=g(k)+t1(k)+t2(k)/2.d0
   60 continue
c
      return
      end
