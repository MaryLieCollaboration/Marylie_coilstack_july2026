      subroutine brkts(h)
c
c     computes poisson brackets of
c     transfer map generator h with each
c     dynamical variable  z(i)
c     pbh(j,i=1,6) contains j-th element
c     of array of coefficients of [h, (i)]
c     pbh(j,i=7,12) contains j-th
c     element of array of coefficients
c     of [h,[h, (i)]].
c     Written by D. Douglas, ca 1982
c
      include 'impli.inc'
      include 'param.inc'
      dimension h(monoms),pb1(monoms),pb2(monoms),pb3(monoms),
     *          pb4(monoms),pb5(monoms)
      include 'pbkh.inc'
c
c     initialize arrays
c
      do 10 i=1,monoms
      pb1(i)=0.0d0
      pb2(i)=0.0d0
      pb3(i)=0.0d0
      do 20 j=1,12
      pbh(i,j)=0.0d0
   20 continue
   10 continue
c
c     compute poisson brackets and store in pbh
c
      m=2
      n=3
      do 30 j=1,6
      k=j+6
      call svpbkt(h,n,j,1,pb1)
      call pbkt(h,n,pb1,m,pb3)
      call pbkt(h,n,pb3,n,pb5)
      do 40 i=7,27
      pbh(i,j)=pbh(i,j)+pb1(i)
   40 continue
      do 45 i=28,83
      pbh(i,k)=pbh(i,k)+pb3(i)
   45 continue
      do 47 i=84,209
      pbh(i,k)=pbh(i,k)+pb5(i)
   47 continue
   30 continue
      m=3
      n=4
      do 50 j=1,6
      call svpbkt(h,n,j,1, pb2)
      call pbkt(h,m,pb2,m,pb4)
      do 60 i=28,83
      pbh(i,j)=pbh(i,j)+pb2(i)
   60 continue
      do 65 i=84,209
      pbh(i,j)=pbh(i,j)+pb4(i)
   65 continue
   50 continue
      return
      end
