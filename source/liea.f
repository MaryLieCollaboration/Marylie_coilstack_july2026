      subroutine polr(fa,fm,rm,pdsm,reval,revec)
c  This subroutine finds the polar decomposition of a symplectic map.
c  fa,fm is the incoming map, and is left unchanged.
c  rm and pdsm are its orthogonal (rotation) and positive definite
c  symmetric factors.  It is assumed that fm has the factorization
c  fm=pdsm*rm.
c  reval and revec are the eigenvalues and eigenvector array for pdsm.
c  Written by Alex Dragt, Fall 1986.  Modified 9/4/91 by Alex Dragt.
c
      include 'impli.inc'
      include 'param.inc'
c
c Calling arrays
      dimension fa(monoms)
      dimension fm(6,6),rm(6,6),pdsm(6,6),reval(6),revec(6,6)
c
c Local arrays
      dimension ta(monoms)
      dimension t1m(6,6),t2m(6,6)
c
c clear array
      call clear(ta,t1m)
c
c begin computation
c
c  computation of positive definite symmetric factor
c  along with its eigenvalues and eigenvectors
c
c  find fm*(fm transpose)
      call matmat(fm,t1m)
      call mtran(t1m)
      call mmult(fm,t1m,t2m)
c  extract square root
      call seig6(t2m,reval,revec)
      call mclear(t2m)
      do 10 i=1,6
      reval(i)=sqrt(reval(i))
      t2m(i,i)=reval(i)
   10 continue
      call matmat(revec,t1m)
      call inv(ta,t1m)
      call sndwch(ta,t1m,ta,t2m,ta,pdsm)
c
c  computation of orthogonal (rotation) factor based on the relation
c  exp(:f2c:)=(script M)(exp:-f2a:)
c
      call matmat(pdsm,t1m)
      call inv(ta,t1m)
      call concat(ta,fm,ta,t1m,ta,rm)
c
      return
      end
