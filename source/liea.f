      subroutine cpsp(f,g,ans1,ans2,ans3,ans4)
c  this subroutine computes the scalar product of the two polynomials
c  f and g.
c  Written by Alex Dragt 10/23/89
c
      include 'impli.inc'
      include 'param.inc'
      include 'expon.inc'
c
c  calling arrays
      dimension f(209), g(209)
c
      integer jf(6),jg(6)
c
c  compute inner products
c
c  first order part
c
      ans1=0.d0
      do 10 indf=1,6
      do 10 indg=1,6
      test=f(indf)*g(indg)
      if (test .ne. 0.d0) then
      do 12 k=1,6
      jf(k)=expon(k,indf)
      jg(k)=expon(k,indg)
   12 continue
      call msp(jf,jg,val)
      ans1=ans1+test*val
      endif
   10 continue
      ans1=ans1/3.d0
c
c  second order part
c
      ans2=0.d0
      do 20 indf=7,27
      do 20 indg=7,27
      test=f(indf)*g(indg)
      if (test .ne. 0.) then
      do 22 k=1,6
      jf(k)=expon(k,indf)
      jg(k)=expon(k,indg)
   22 continue
      call msp(jf,jg,val)
      ans2=ans2+test*val
      endif
   20 continue
      ans2=ans2/12.d0
c
c  third order part
c
      ans3=0.d0
      do 30 indf=28,83
      do 30 indg=28,83
      test=f(indf)*g(indg)
      if (test .ne. 0.d0) then
      do 32 k=1,6
      jf(k)=expon(k,indf)
      jg(k)=expon(k,indg)
   32 continue
      call msp(jf,jg,val)
      ans3=ans3+test*val
      endif
   30 continue
      ans3=ans3/60.d0
c
c  fourth order part
c
      ans4=0.d0
      do 40 indf=84,209
      do 40 indg=84,209
      test=f(indf)*g(indg)
      if (test .ne. 0.) then
      do 42 k=1,6
      jf(k)=expon(k,indf)
      jg(k)=expon(k,indg)
   42 continue
      call msp(jf,jg,val)
      ans4=ans4+test*val
      endif
   40 continue
      ans4=ans4/360.d0
c
      return
      end
