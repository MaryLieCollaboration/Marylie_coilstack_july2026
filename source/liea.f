      subroutine fxform(ga,gm,fa,ha)
c This is a subroutine for transforming a function f.
c That is, it  computes h=exp(:g:)f where f is given
c by f=f1+f2+f3+f4 and exp(:g:) denotes a general map.
c Presently f1 is transformed only by the linear part of exp(:g:).
c Written by Alex Dragt, Fall 1986.
c Modified by Alex Dragt, 10/28/89.
c
      include 'impli.inc'
      include 'param.inc'
c
c Calling arrays
c
      dimension ga(monoms),fa(monoms),ha(monoms)
      dimension gm(6,6)
c
c Working arrays
c
      dimension t1a(monoms),t2a(monoms),t3a(monoms)
      dimension tm(6,6)
c
c clear arrays
c
      call clear(t1a,tm)
      call clear(t2a,tm)
      call clear(t3a,tm)
      call clear(ha,tm)
c
c compute various poisson brackets
c
c compute [g3,f2]
      call pbkt(ga,3,fa,2,t1a)
c compute [g3,f3]
      call pbkt(ga,3,fa,3,t2a)
c compute [g3,[g3,f2]]
      call pbkt(ga,3,t1a,3,t3a)
c compute [g4,f2]
      call pbkt(ga,4,fa,2,t1a)
c
c accumulate results
c
c set up first order part
      do 5 i=1,6
    5 t1a(i)=fa(i)
c set up second order part
      do 10 i=7,27
   10 t1a(i)=fa(i)
c set up third order part
      do 20 i=28,83
   20 t1a(i)=fa(i) + t1a(i)
c set up fourth order part
      do 30 i=84,209
   30 t1a(i)=fa(i) + t2a(i) + t3a(i)/2.d0 + t1a(i)
c
c transform results by gm
c
      call xform(t1a,1,gm,0,ha)
      call xform(t1a,2,gm,1,ha)
      call xform(t1a,3,gm,1,ha)
      call xform(t1a,4,gm,1,ha)
c
      return
      end
